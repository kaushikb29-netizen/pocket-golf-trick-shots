const BORDER_T = 22;

function makeBoxBorders(
  left: number,
  top: number,
  right: number,
  bottom: number,
  prefix: string
): RectWall[] {
  const width = right - left;
  const height = bottom - top;
  return [
    {
      id: `${prefix}-top`,
      x: left + width / 2,
      y: top - BORDER_T / 2,
      w: width + BORDER_T * 2,
      h: BORDER_T,
      angle: 0,
      kind: 'border',
    },
    {
      id: `${prefix}-bottom`,
      x: left + width / 2,
      y: bottom + BORDER_T / 2,
      w: width + BORDER_T * 2,
      h: BORDER_T,
      angle: 0,
      kind: 'border',
    },
    {
      id: `${prefix}-left`,
      x: left - BORDER_T / 2,
      y: top + height / 2,
      w: BORDER_T,
      h: height,
      angle: 0,
      kind: 'border',
    },
    {
      id: `${prefix}-right`,
      x: right + BORDER_T / 2,
      y: top + height / 2,
      w: BORDER_T,
      h: height,
      angle: 0,
      kind: 'border',
    },
  ];
}

